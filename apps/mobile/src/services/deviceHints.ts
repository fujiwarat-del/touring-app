// ============================================================
// 背景での位置取得に関する端末設定の案内
//
// 【背景】多くの Android 端末は、メーカー独自の省電力機構によって
// 前面サービスであっても背景の位置取得を止めてしまう。実機検証では、
// 最近のアプリ画面でアプリをロックしないと取得率が 3〜15% まで落ち、
// ロックすると約100%まで回復した。自動起動・バックグラウンドランニング・
// 電池最適化をすべて許可しても、ロックしないと止まる。
//
// 【なぜメーカーで出し分けないか】
// 当初は Xiaomi 系などを列挙して判定していたが、検証端末の nubia が
// リストから漏れて案内が出なかった。Meizu / OnePlus / ASUS / Infinix など
// 同じ挙動の端末は多く、列挙し続ける限り取りこぼしは無くならない。
// 該当しない端末に余計な案内が出る害より、該当する端末で出ない害の方が
// 大きいため、Android では無条件に案内する。
//
// 【ロック状態は判定できない】
// ロックされているかを知る API は Android に無い。したがって
// 「ロックされていなければ警告する」という作りにはできず、
// 常に案内を出したうえで、待つ側に鮮度（最終更新からの経過）を見せて
// 古い情報を信用させない、という二段構えで対処する。
// ============================================================

import { Platform } from 'react-native';

export function needsBackgroundHint(): boolean {
  return Platform.OS === 'android';
}

export const BACKGROUND_HINT = {
  title: 'タスクロックをお願いします',
  body:
    'Android では、画面を消すとアプリの位置取得が止められてしまうことがあります。\n\n' +
    '最近のアプリ（タスク一覧）を開き、このアプリのカードを長押しして' +
    '鍵アイコンをタップしてください。\n\n' +
    'ロックしないと、到着予定が途中で更新されなくなります。',
};

/** 画面内に常設する短い案内。ダイアログを見落としても伝わるように */
export const BACKGROUND_HINT_INLINE =
  '⚠️ 最近のアプリ画面でこのアプリを長押しし、鍵アイコンでロックしてください。' +
  'ロックしないと走行中に更新が止まります。';
